/**
 * Generate src/gif-font.ts, the bitmap font gif.ts uses for action labels.
 *
 *   npx tsx scripts/generate-gif-font.ts
 *
 * Renders printable ASCII (32-126) in a monospace font on a canvas in
 * headless Chromium, thresholds each 8x16 cell, and writes one hex string
 * per glyph (two hex digits per row, high bit = leftmost pixel). Run it only
 * to change the font; the output is committed.
 */

import { writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";
import { chromium } from "patchright";

// The DOM lib isn't included; this global exists only inside page.evaluate
declare const document: any;

const WIDTH = 8;
const HEIGHT = 16;
const FONT = "bold 13px Menlo, Consolas, 'DejaVu Sans Mono', monospace";
const BASELINE = 12;

const browser = await chromium.launch({ headless: true });
const page = await browser.newPage();
const glyphs = await page.evaluate(
  ({ width, height, font, baseline }) => {
    const canvas = document.createElement("canvas");
    canvas.width = width;
    canvas.height = height;
    const ctx = canvas.getContext("2d")!;
    const out: string[] = [];
    for (let code = 32; code <= 126; code++) {
      ctx.clearRect(0, 0, width, height);
      ctx.font = font;
      ctx.fillStyle = "#000";
      ctx.textBaseline = "alphabetic";
      ctx.fillText(String.fromCharCode(code), 0, baseline);
      const { data } = ctx.getImageData(0, 0, width, height);
      let hex = "";
      for (let y = 0; y < height; y++) {
        let row = 0;
        for (let x = 0; x < width; x++) {
          if (data[(y * width + x) * 4 + 3]! >= 110) row |= 0x80 >> x;
        }
        hex += row.toString(16).padStart(2, "0");
      }
      out.push(hex);
    }
    return out;
  },
  { width: WIDTH, height: HEIGHT, font: FONT, baseline: BASELINE }
);
await browser.close();

const target = join(dirname(fileURLToPath(import.meta.url)), "..", "src", "gif-font.ts");
writeFileSync(
  target,
  `// Generated by scripts/generate-gif-font.ts. Don't edit by hand.
// Printable ASCII (32-126), ${WIDTH}x${HEIGHT} cells, two hex digits per row, high bit leftmost.

export const GLYPH_WIDTH = ${WIDTH};
export const GLYPH_HEIGHT = ${HEIGHT};

export const GLYPHS: readonly string[] = [
${glyphs.map((g, i) => `  "${g}", // ${JSON.stringify(String.fromCharCode(32 + i))}`).join("\n")}
];
`
);
console.log(`Wrote ${glyphs.length} glyphs to ${target}`);
